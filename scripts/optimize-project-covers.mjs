import sharp from 'sharp';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const images = new URL('../src/assets/images/', import.meta.url);
const output = new URL('previews/', images);
const covers = [
  'jirama_dashboard.png', 'mathstools_cap1.png', 'cvbuilder_cover.png',
  'konexmoney_cap1.jpg', 'sakafomarket_cap1.png', 'lunahygiene_cap1.jpg',
];
await mkdir(output, { recursive: true });
const imports = [];
const entries = [];
for (const [index, filename] of covers.entries()) {
  const name = filename.replace(/\.[^.]+$/, '');
  imports.push(`import original${index} from '../assets/images/${filename}';`);
  for (const width of [480, 960]) {
    const target = `${name}-${width}.webp`;
    const info = await sharp(fileURLToPath(new URL(filename, images)))
      .resize(width, width * 10 / 16, { fit: 'cover', position: 'centre' })
      .webp({ quality: 82 })
      .toFile(fileURLToPath(new URL(target, output)));
    imports.push(`import preview${index}_${width} from '../assets/images/previews/${target}';`);
    console.log(`${target}: ${info.size} bytes`);
  }
  entries.push(`  [original${index}]: { src: preview${index}_960, srcSet: preview${index}_480 + ' 480w, ' + preview${index}_960 + ' 960w' },`);
}
await writeFile(new URL('../src/data/projectThumbnails.ts', import.meta.url),
  '// Generated by scripts/optimize-project-covers.mjs. Originals remain available in project details.\n' +
  imports.join('\n') + '\n\nexport const projectThumbnails: Record<string, { src: string; srcSet: string }> = {\n' +
  entries.join('\n') + '\n};\n');
